def bits(rows: str):
    """'##### ..... ...' → 5 列（列主序），bit0 = 顶行。"""
    grid = [r for r in rows.split(' ') if r]
    assert len(grid) == 7, f'字形需要 7 行，实际 {len(grid)}'
    cols = []
    for x in range(5):
        v = 0
        for y in range(7):
            ch = grid[y][x]
            assert ch in '#.', f'非法字符 {ch!r}'
            if ch == '#':
                v |= (1 << y)
        cols.append(v)
    return cols


def main() -> int:
    sys.stdout.write('// 内置 5x7 位图字体（ASCII 32..126；列主序：每字形 5 列，bit0 = 顶行）\n')
    sys.stdout.write('// 由 tools/font_gen.py 生成，请勿手工编辑。\n')
    sys.stdout.write('static const uint8_t kBuiltin5x7[95][5] = {\n')
    for cp in range(32, 127):
        ch = chr(cp)
        # 小写复用大写形状
        src = GLYPHS.get(ch)
        if src is None and ch.isalpha():
            src = GLYPHS.get(ch.upper())
        if src is None:
            src = GLYPHS[' ']
        cols = bits(src)
        name = ch if ch not in ('\\', "'") else ('backslash' if ch == '\\' else 'quote')
        sys.stdout.write('    { %s },  // %s (U+%04X)\n'
                         % (', '.join('0x%02X' % c for c in cols), name, cp))
    sys.stdout.write('};\n')
    return 0


