// scn.Button：(x, y) = 命中矩形左下角；命中 = [x,x+w]×[y,y+h]。
function makeButton(name, x, y, w, h, color) {
  var id = newUiEntity('scn.Button');
  if (id < 0) return -1;
  node_set_name(id, name);
  node_set_number(id, 'scn.Button', 'x', x);
  node_set_number(id, 'scn.Button', 'y', y);
  node_set_number(id, 'scn.Button', 'width', w);
  node_set_number(id, 'scn.Button', 'height', h);
  node_set_number(id, 'scn.Button', 'z', 0);
  setButtonColor(id, color);
  return id;
}

// 正方形按钮 + 内部居中文字（两个独立实体：按钮不渲染自带 label）。
function makeButtonWithText(name, x, y, size, color, text, fontSize, textColor) {
  var id = makeButton(name, x, y, size, size, color);
  var tx = x + (size - estimateTextWidth(text, fontSize)) / 2;
  makeLabel(name + '_text', tx, y + (size + fontSize) / 2, text, fontSize, textColor);
  return id;
}

// 半透明底栏（scn.Sprite 矩形 + 节点透明度；位置 = 中心，需要 Transform2D 才能逐帧保留位置）。
function makeRect(name, cx, cy, w, h, color, opacity) {
  var id = entity_spawn();
  if (id < 0) return -1;
  node_set_name(id, name);
  node_add_component(id, 'scn.Transform2D');
  node_add_component(id, 'scn.Sprite');
  node_set_position(id, cx, cy);
  node_set_number(id, 'scn.Sprite', 'width', w);
  node_set_number(id, 'scn.Sprite', 'height', h);
  node_set_number(id, 'scn.Sprite', 'r', color[0]);
  node_set_number(id, 'scn.Sprite', 'g', color[1]);
  node_set_number(id, 'scn.Sprite', 'b', color[2]);
  node_set_opacity(id, opacity);
  return registerUi(id);
}

// 条目行按钮：正常 = 单个宽矩形；RECT_BUTTONS=false 时用 h×h 方块平铺成同尺寸条带。
// 返回按钮 id 数组（正常只有 1 个）。
function makeRowButton(name, x, y, w, h, color) {
  if (RECT_BUTTONS) {
    var one = makeButton(name, x, y, w, h, color);
    return one >= 0 ? [one] : [];
  }
  var n = Math.max(1, Math.round(w / h));
  var tw = w / n;
  var ids = [];
  for (var k = 0; k < n; k++) {
    var id = makeButton(k === 0 ? name : name + '_t' + String(k), x + k * tw, y, tw, h, color);
    if (id >= 0) ids.push(id);
  }
  return ids;
}

// ---- 模式判定 / 状态 -----------------------------------------------------

function pageCount() {
  var n = MODELS.length;
  if (n <= 0) return 1;
  return Math.max(1, Math.ceil(n / PER_PAGE));
}
function pageStart() {
  return S.page * PER_PAGE;
}
function pageItemCount() {
  var remain = MODELS.length - pageStart();
  if (remain < 0) remain = 0;
  return remain < PER_PAGE ? remain : PER_PAGE;
}

// 当前场景对应的模型下标（-1 = 不是 demo 场景）。
// 主路径：标题（demo 场景的 title == 模型名）；兜底：场景目录名（<base>/<Model>）。
function currentModelIndex() {
  var title = apiSceneTitle();
  var i = MODELS.indexOf(title);
  if (i >= 0) return i;
  var dir = apiSceneDir();
  if (!dir) dir = dirOf(apiScenePath());
  i = MODELS.indexOf(baseNameOf(dir));
  return i;
}

// 首次 on_start：把画廊根目录 / 入口路径 / 入口标题固化下来（之后切场景不变）。
function captureBase(title) {
  if (S.base) return;
  var dir = normPath(apiSceneDir());
  var path = normPath(apiScenePath());
  if (!dir) dir = dirOf(path);
  if (!dir) dir = '.';
  S.base = dir;
  S.entry = path ? path : pathJoin(dir, 'index.scn');
  S.entryTitle = title ? title : 'Khronos glTF Sample Assets';
}

// ---- 场景切换 ------------------------------------------------------------

function scenePathFor(model) {
  return pathJoin(S.base, model, model + '.scn');
}

// 进入第 gi 个模型（gi = MODELS 下标）。
function openModel(gi) {
  if (gi < 0 || gi >= MODELS.length) return;
  var path = scenePathFor(MODELS[gi]);
  log('gallery: open ' + path);
  director_load_scene(path);
}

// demo 内切换上一个/下一个（排序列表内**循环**）。
function stepModel(delta) {
  var n = MODELS.length;
  if (n <= 0 || S.demoIndex < 0) return;
  var idx = (S.demoIndex + delta) % n;
  if (idx < 0) idx += n;
  openModel(idx);
}

// 返回列表：回到当前模型所在的那一页。
function backToList() {
  if (S.demoIndex >= 0) S.page = Math.floor(S.demoIndex / PER_PAGE);
  var path = S.entry ? S.entry : pathJoin(S.base, 'index.scn');
  log('gallery: back ' + path);
  director_load_scene(path);
}

// 画廊内翻页（循环）。
function changePage(delta) {
  var tp = pageCount();
  if (tp <= 1) return;
  S.page = (S.page + delta + tp) % tp;
  rebuildUi();
  log('[gallery] mode=gallery page=' + String(S.page + 1) + '/' + String(tp) +
      ' items=' + String(pageItemCount()));
}

// ---- 构建：画廊模式 ------------------------------------------------------

function buildGallery() {
  var total = MODELS.length;
  var tp = pageCount();
  var start = pageStart();
  var count = pageItemCount();

  // 背景（2D 场景；clear 设置的是引擎持久背景色，每帧无需重复）
  clear(C_BG[0], C_BG[1], C_BG[2]);
  S.hoverItem = -1;

  makeLabel('gallery_title', 40, 674, S.entryTitle + ' · ' + String(total) + ' models',
            28, C_TITLE);
  makeLabel('gallery_hint', 40, 636, '点击模型进入演示 · Left / Right 翻页', 14, C_HINT);

  if (total <= 0) {
    makeLabel('gallery_empty', 40, 560,
              'MODELS 为空：先运行 python tools/gen_khronos_gallery.py 生成模型列表',
              18, C_HINT);
    return;
  }

  // 分页列表：行优先（item_0/item_1 同一行，两列）
  for (var i = 0; i < count; i++) {
    var row = Math.floor(i / COLS);
    var col = i % COLS;
    var gi = start + i;
    var bx = COL_X[col];
    var by = LIST_TOP - row * ROW_PITCH - ROW_H;
    var ids = makeRowButton('item_' + String(i), bx, by, COL_W, ROW_H, C_ROW);
    if (!ids.length) continue;
    if (!S.itemButtons[i]) S.itemButtons[i] = [];
    for (var k = 0; k < ids.length; k++) {
      S.rowOf[ids[k]] = i;
      S.itemButtons[i].push(ids[k]);
    }
    // 条目文字（Button 不渲染 label）→ 独立 Label，垂直居中于按钮
    makeLabel('item_label_' + String(i), bx + 14, by + (ROW_H + ITEM_FONT) / 2,
              fitText(MODELS[gi], COL_W - 28, ITEM_FONT), ITEM_FONT, C_TEXT);
  }

  // 底部分页栏：上页 / 页码 / 下页（整体居中）
  var pageText = String(S.page + 1) + ' / ' + String(tp);
  var labelW = estimateTextWidth(pageText, 22);
  var groupW = PAGE_BTN + 20 + labelW + 20 + PAGE_BTN;
  var gx = (W - groupW) / 2;
  S.pagePrev = makeButtonWithText('page_prev', gx, PAGE_BAR_Y, PAGE_BTN, C_BTN,
                                  '上页', 15, C_BTN_TEXT);
  // Label 的 y 是**文字上沿**（文字向下排）→ 垂直居中 = 按钮中心 y + 字号/2
  makeLabel('page_label', gx + PAGE_BTN + 20,
            PAGE_BAR_Y + (PAGE_BTN + 22) / 2, pageText, 22, C_TITLE);
  S.pageNext = makeButtonWithText('page_next', gx + PAGE_BTN + 20 + labelW + 20,
                                  PAGE_BAR_Y, PAGE_BTN, C_BTN, '下页', 15, C_BTN_TEXT);
}

